# <<< README texts.

# ---- step 1: make your move (pwd, ls, cd, cd ..; the flag is a file name) ----
F1=$(flag moves); keep 1 "$F1"
set -- $(printf '%s\n' park library market harbor station arcade | shuf | head -n 3)
wrong=$1; right=$2; other=$3
mid=$(pick fountain gazebo tunnel bridge kiosk); end=$(pick locker crate shed cellar toolbox)
M1="$H/mission1"; T1="$M1/town"; E1="$T1/$right/$mid/$end"
mkdir -p "$T1/$wrong" "$T1/$other" "$E1"
touch "$M1/start-here--go-into-town" \
      "$T1/sign--go-into-the-$wrong" \
      "$T1/$wrong/dead-end--go-back-up-and-try-the-$right" \
      "$T1/$other/nothing-here--go-back-up" \
      "$T1/$right/go-into-the-$mid-then-the-$end" \
      "$T1/$right/$mid/almost-there--keep-going-into-the-$end" \
      "$E1/you-made-it--the-flag-is-the-file-name" \
      "$E1/$F1"
readme home > "$H/README.txt"
F0=$(flag warmup); keep 0 "$F0"
{ readme orientation; echo "  $F0"; } > "$H/orientation.txt"
readme 1 > "$M1/README.txt"

# ---- step 2: let the cat out of the bag (cat --help shows -n) ----
F2=$(flag cat); keep 2 "$F2"
mkdir -p "$H/mission2"
line=$(shuf -i 30-95 -n1)
{ printf 'The cat is hiding in bag.txt.\nEvery line in the bag looks like a flag, but only line %s is real.\n\n' "$line"; readme 2; } > "$H/mission2/README.txt"
for i in $(seq 1 100); do
  if [ "$i" -eq "$line" ]; then echo "meow $F2"; else echo "meow CYBA{cat-$(head -c 4 /dev/urandom | od -An -tx1 | tr -d ' \n')}"; fi
done > "$H/mission2/bag.txt"

# ---- step 3: hidden file (ls -a) ----
F3=$(flag hidden); keep 3 "$F3"
mkdir -p "$H/mission3"
readme 3 > "$H/mission3/README.txt"
echo "Nothing to see here. Or is there? Some files are shy." > "$H/mission3/notes.txt"
echo "Close, but this hidden file is a decoy." > "$H/mission3/.old-$(rnd 4)"
printf 'You found the hidden file.\nFlag: %s\n' "$F3" > "$H/mission3/.$(pick treasure stash secret-notes backup-codes)"

# ---- step 4: find by name ----
F4=$(flag finder); keep 4 "$F4"
ext=$(pick key gem relic)
for a in alpha bravo charlie delta echo; do
  for b in 1 2 3 4; do
    d="$H/mission4/archive/$a/$(pick box bin shelf drawer)-$(rnd 4)"; mkdir -p "$d"
    for _ in 1 2 3 4; do echo "junk $(rnd 20)" > "$d/$(rnd 6).$(pick txt log dat)"; done
  done
done
target="$(find "$H/mission4/archive" -mindepth 2 -type d | shuf -n1)/$(rnd 6).$ext"
printf 'Flag: %s\n' "$F4" > "$target"
{ printf 'Somewhere in archive/ is ONE file ending in .%s\nIt holds the flag.\n\n' "$ext"; readme 4; } > "$H/mission4/README.txt"

# ---- step 5: grep a log ----
F5=$(flag grep); keep 5 "$F5"
who=$(pick nightowl ghost_fox zero_cool red_panda pixel_wolf)
mkdir -p "$H/mission5"
# awk only, so the setup needs nothing beyond a stock Ubuntu image
awk -v who="$who" -v flag="$F5" -v seed="$RANDOM$RANDOM" 'BEGIN {
  srand(seed); split("alice bob carol dave erin frank grace heidi ivan judy", u, " ")
  split("LOGIN_OK LOGIN_FAIL VIEW_PAGE DOWNLOAD LOGOUT", a, " ")
  hit = 5000 + int(rand() * 30000)
  for (i = 0; i < 40000; i++) {
    t = 8 * 3600 + i
    stamp = sprintf("%02d:%02d:%02d", int(t / 3600) % 24, int(t / 60) % 60, t % 60)
    if (i == hit) printf "%s user=%s action=LOGIN_OK token=%s\n", stamp, who, flag
    else printf "%s user=%s action=%s token=%08x\n", stamp, u[1 + int(rand() * 10)], a[1 + int(rand() * 5)], int(rand() * 4294967295)
  }
}' > "$H/mission5/access.log"
{ printf 'An intruder logged in ONCE as:  %s\nTheir token is the flag.\n\n' "$who"; readme 5; } > "$H/mission5/README.txt"

# ---- step 8: base64 ----
F6=$(flag decoded); keep 8 "$F6"
mkdir -p "$H/mission8"
readme 8 > "$H/mission8/README.txt"
printf 'Decoded! Encoding is not encryption.\nFlag: %s\n' "$F6" | base64 -w 40 > "$H/mission8/message.b64"

# ---- step 6: odd one out (sort | uniq -u) ----
F7=$(flag odd); keep 6 "$F7"
mkdir -p "$H/mission6"; readme 6 > "$H/mission6/README.txt"
awk -v flag="$F7" -v seed="$RANDOM$RANDOM" 'BEGIN {
  srand(seed); n = 0
  for (i = 0; i < 300; i++) {
    h = ""; for (k = 0; k < 8; k++) h = h substr("0123456789abcdef", 1 + int(rand() * 16), 1)
    c = 2 + int(rand() * 3); for (j = 0; j < c; j++) L[++n] = "CYBA{odd-" h "}"
  }
  L[++n] = flag
  for (i = n; i > 1; i--) { j = 1 + int(rand() * i); t = L[i]; L[i] = L[j]; L[j] = t }
  for (i = 1; i <= n; i++) print L[i]
}' > "$H/mission6/codes.txt"

# ---- step 7: permission denied (ls -l, chmod +x) ----
F8=$(flag exec); keep 7 "$F8"
mkdir -p "$H/mission7"; readme 7 > "$H/mission7/README.txt"
printf 'Access granted.\nFlag: %s\n' "$F8" | base64 > "$H/mission7/.door"
printf '#!/bin/sh\n# The vault door. It only opens when this file has execute permission.\nbase64 -d ~/mission7/.door\n' > "$H/mission7/unlock.sh"
chmod 644 "$H/mission7/unlock.sh"

# ---- step 9: layer cake (base64 4 to 6 times) ----
F9=$(flag layers); keep 9 "$F9"
mkdir -p "$H/mission9"; readme 9 > "$H/mission9/README.txt"
cake=$(printf 'Flag: %s\n' "$F9")
for _ in $(seq 1 $((4 + RANDOM % 3))); do cake=$(printf '%s\n' "$cake" | base64); done
printf '%s\n' "$cake" > "$H/mission9/cake.b64"

# ---- step 10: endgame (find + grep/cut/base64 + chmod), Very Hard ----
hex3() { head -c 3 /dev/urandom | od -An -tx1 | tr -d ' \n'; }
p1=$(hex3); p2=$(hex3); p3=$(hex3)
F10="CYBA{$p1-$p2-$p3}"; keep 10 "$F10"
M="$H/mission10"; mkdir -p "$M"
who10=$(pick shadow_byte cipher_cat glitch root_kit null_ptr)
vdirs=()
for a in north south east west; do
  for b in rack shelf crate; do
    d="$M/vault/$a/$b-$(rnd 3)"; mkdir -p "$d"; vdirs+=("$d")
    for _ in 1 2 3; do echo "junk $(rnd 16)" > "$d/$(rnd 5).$(pick txt log cfg)"; done
  done
done
mapfile -t hn < <(printf '%s\n' .cache .backup .tmp .notes .stash .keep | shuf)
for i in 0 1 2; do echo "Nothing here. Keep looking." > "${vdirs[RANDOM % ${#vdirs[@]}]}/${hn[$i]}"; done
echo "piece 1: $p1" > "${vdirs[RANDOM % ${#vdirs[@]}]}/${hn[3]}"
tok=$(printf 'piece 2: %s' "$p2" | base64)
awk -v who="$who10" -v tok="$tok" -v seed="$RANDOM$RANDOM" 'BEGIN {
  srand(seed); split("alice bob carol dave erin frank grace heidi ivan judy", u, " ")
  split("LOGIN_OK LOGIN_FAIL SUDO SSH_KEY LOGOUT", a, " ")
  b = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
  hit = 500 + int(rand() * 2000)
  for (i = 0; i < 3000; i++) {
    t = 20 * 3600 + i * 7
    stamp = sprintf("%02d:%02d:%02d", int(t / 3600) % 24, int(t / 60) % 60, t % 60)
    if (i == hit) { printf "%s user=%s action=LOGIN_OK token=%s\n", stamp, who, tok; continue }
    s = ""; for (k = 0; k < 20; k++) s = s substr(b, 1 + int(rand() * 64), 1)
    printf "%s user=%s action=%s token=%s\n", stamp, u[1 + int(rand() * 10)], a[1 + int(rand() * 5)], s
  }
}' > "$M/auth.log"
printf 'piece 3: %s\n' "$p3" | base64 | base64 > "$M/.door"
printf '#!/bin/sh\n# The last door. It only opens when this file has execute permission.\nbase64 -d ~/mission10/.door | base64 -d\n' > "$M/unlock.sh"
chmod 644 "$M/unlock.sh"
{ printf 'The flag is CYBA{piece1-piece2-piece3}: three pieces, joined with dashes.\n  Piece 1: in a hidden file somewhere under vault/  (some hidden files are decoys)\n  Piece 2: %s logged in once in auth.log. Their token is base64.\n  Piece 3: whatever unlock.sh prints.\n\n' "$who10"; readme 10; } > "$M/README.txt"

# ---- the submit command ----
cat > /usr/local/bin/submit <<'SH'
#!/bin/bash
# Usage: submit <flag>   records your answer, then press CHECK in the instructions.
if [ -z "${1:-}" ]; then echo "Usage: submit CYBA{...}"; exit 1; fi
echo "$1" >> "$HOME/.answers"
echo "Recorded. Now press CHECK in the instructions panel."
SH
chmod 755 /usr/local/bin/submit

touch "$H/.answers"
