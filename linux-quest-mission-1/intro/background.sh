#!/bin/bash
# Runs hidden, as root, when the scenario starts. Builds the six missions with fresh
# random flags every time, so no two students (and no two runs) share answers.
set -euo pipefail
Q=/root/.quest            # SHA-256 fingerprints of the flags (never the flags)
H=/home/player            # the student plays as this unprivileged user
mkdir -p "$Q"; chmod 700 "$Q"
id player >/dev/null 2>&1 || useradd -m -s /bin/bash player

flag() { printf 'CYBA{%s-%s}' "$1" "$(head -c 4 /dev/urandom | od -An -tx1 | tr -d ' \n')"; }
keep() { printf '%s' "$2" | sha256sum | cut -d' ' -f1 > "$Q/$1"; }
pick() { printf '%s\n' "$@" | shuf -n1; }
rnd()  { head -c 32 /dev/urandom | base64 | tr -dc 'a-z0-9' | cut -c1-"$1"; }

# >>> README texts. Generated by guest/make-missions.py: edit that file, not this block.
readme() {
  case "$1" in
    home) cat <<'EOF'
CyberQuest Linux CTF
====================

This file explains the game. Each mission folder has its own README.txt
with that mission's instructions. Read one with:  cat README.txt

How to play
  1. Go to a mission:    cd ~/mission1
  2. Look around:        ls
  3. Read its brief:     cat README.txt
  4. Find the flag. It looks like CYBA{word-1a2b3c4d}
  5. Check it:           submit CYBA{...}     then press CHECK

Missions
  1  Make your move               Easy       100 pts
  2  Let the cat out of the bag   Easy       100 pts
  3  Now you see me               Easy       100 pts
  4  Needle in the tree           Medium     200 pts
  5  Search party                 Medium     200 pts
  6  Decoder ring                 Hard       400 pts
                                            1100 pts

Flags change every time the scenario starts.
EOF
    ;;
    1) cat <<'EOF'
Mission 1: Make your move   [Easy, 100 points]

Objective: Navigate the file system using basic Linux commands to find the flag.

  cd ~/mission1
  ls

Moving around is the first real skill on the command line:

  pwd         where am I?
  ls          what is in this folder?
  cd NAME     move into a folder
  cd ..       go back up one level
  cd ~        go home

A flag is waiting at the end of a trail that starts in ~/mission1.
Nothing on this trail needs opening: the file names are the signposts.
Use ls to read them and cd to follow them. Some turns are dead ends.

At the end of the trail, ls shows you the flag itself.

Useful commands: pwd, ls, cd
When you have the flag: submit CYBA{...}, then press CHECK.
EOF
    ;;
    2) cat <<'EOF'
Mission 2: Let the cat out of the bag   [Easy, 100 points]

Objective: Read files with cat, and use --help to number the lines.

  cd ~/mission2
  cat README.txt

cat prints a file on the screen. You just used it to read README.txt.

The cat is hiding in bag.txt: 100 lines, and every one looks like a
flag. Only the line number in README.txt is real. Counting 100 lines by
hand is how mistakes happen.

Almost every Linux command can explain itself: type its name, a space,
then --help. Ask cat for its help and look for an option that numbers
the lines. You will use --help in every mission after this one.

Useful command: cat
When you have the flag: submit CYBA{...}, then press CHECK.
EOF
    ;;
    3) cat <<'EOF'
Mission 3: Now you see me   [Easy, 100 points]

Objective: Reveal the hidden files and find the real flag.

  cd ~/mission3
  ls

There is a flag in this folder, but plain ls will not show it.

On Linux, a file whose name starts with a dot is hidden. Watch out: one
hidden file is a decoy.

Useful commands: ls, cat
When you have the flag: submit CYBA{...}, then press CHECK.
EOF
    ;;
    4) cat <<'EOF'
Mission 4: Needle in the tree   [Medium, 200 points]

Objective: Search a folder tree by file name to find the flag.

  cd ~/mission4
  cat README.txt

The archive folder holds about 80 files in 20 folders. Exactly one of
them has the file ending named in README.txt, and it holds the flag.

Opening folders one by one is too slow. Let the computer search.

Useful commands: find, cat
When you have the flag: submit CYBA{...}, then press CHECK.
EOF
    ;;
    5) cat <<'EOF'
Mission 5: Search party   [Medium, 200 points]

Objective: Search a huge log for the intruder's line.

  cd ~/mission5
  cat README.txt

access.log has 40,000 lines. One intruder logged in exactly once.

Their token on that line is the flag. Scrolling would take all day.

Useful commands: grep, head, wc
When you have the flag: submit CYBA{...}, then press CHECK.
EOF
    ;;
    6) cat <<'EOF'
Mission 6: Decoder ring   [Hard, 400 points]

Objective: Decode a base64 message to reveal the flag.

  cd ~/mission6
  cat message.b64

It looks like gibberish, but it is not encrypted. It is encoded with
base64: a way of writing any data using only letters, digits, +, / and
=.

There is no secret key. Anyone can decode it.

Useful command: base64
When you have the flag: submit CYBA{...}, then press CHECK.
EOF
    ;;
  esac
}
# <<< README texts.

# ---- step 1: make your move (pwd, ls, cd, cd ..; the flag is a file name) ----
F1=$(flag moves); keep 1 "$F1"
set -- $(printf '%s\n' park library market harbor station arcade | shuf | head -n 3)
wrong=$1; right=$2; other=$3
mid=$(pick fountain gazebo tunnel bridge kiosk); end=$(pick locker crate shed cellar toolbox)
M1="$H/mission1"; T1="$M1/town"; E1="$T1/$right/$mid/$end"
mkdir -p "$T1/$wrong" "$T1/$other" "$E1"
touch "$M1/start-here--go-into-town" \
      "$T1/sign--go-into-the-$wrong" \
      "$T1/$wrong/dead-end--go-back-up-and-try-the-$right" \
      "$T1/$other/nothing-here--go-back-up" \
      "$T1/$right/go-into-the-$mid-then-the-$end" \
      "$T1/$right/$mid/almost-there--keep-going-into-the-$end" \
      "$E1/you-made-it--the-flag-is-the-file-name" \
      "$E1/$F1"
readme home > "$H/README.txt"
readme 1 > "$M1/README.txt"

# ---- step 2: let the cat out of the bag (cat --help shows -n) ----
F2=$(flag cat); keep 2 "$F2"
mkdir -p "$H/mission2"
line=$(shuf -i 30-95 -n1)
{ printf 'The cat is hiding in bag.txt.\nEvery line in the bag looks like a flag, but only line %s is real.\n\n' "$line"; readme 2; } > "$H/mission2/README.txt"
for i in $(seq 1 100); do
  if [ "$i" -eq "$line" ]; then echo "meow $F2"; else echo "meow CYBA{cat-$(head -c 4 /dev/urandom | od -An -tx1 | tr -d ' \n')}"; fi
done > "$H/mission2/bag.txt"

# ---- step 3: hidden file (ls -a) ----
F3=$(flag hidden); keep 3 "$F3"
mkdir -p "$H/mission3"
readme 3 > "$H/mission3/README.txt"
echo "Nothing to see here. Or is there? Some files are shy." > "$H/mission3/notes.txt"
echo "Close, but this hidden file is a decoy." > "$H/mission3/.old-$(rnd 4)"
printf 'You found the hidden file.\nFlag: %s\n' "$F3" > "$H/mission3/.$(pick treasure stash secret-notes backup-codes)"

# ---- step 4: find by name ----
F4=$(flag finder); keep 4 "$F4"
ext=$(pick key gem relic)
for a in alpha bravo charlie delta echo; do
  for b in 1 2 3 4; do
    d="$H/mission4/archive/$a/$(pick box bin shelf drawer)-$(rnd 4)"; mkdir -p "$d"
    for _ in 1 2 3 4; do echo "junk $(rnd 20)" > "$d/$(rnd 6).$(pick txt log dat)"; done
  done
done
target="$(find "$H/mission4/archive" -mindepth 2 -type d | shuf -n1)/$(rnd 6).$ext"
printf 'Flag: %s\n' "$F4" > "$target"
{ printf 'Somewhere in archive/ is ONE file ending in .%s\nIt holds the flag.\n\n' "$ext"; readme 4; } > "$H/mission4/README.txt"

# ---- step 5: grep a log ----
F5=$(flag grep); keep 5 "$F5"
who=$(pick nightowl ghost_fox zero_cool red_panda pixel_wolf)
mkdir -p "$H/mission5"
# awk only, so the setup needs nothing beyond a stock Ubuntu image
awk -v who="$who" -v flag="$F5" -v seed="$RANDOM$RANDOM" 'BEGIN {
  srand(seed); split("alice bob carol dave erin frank grace heidi ivan judy", u, " ")
  split("LOGIN_OK LOGIN_FAIL VIEW_PAGE DOWNLOAD LOGOUT", a, " ")
  hit = 5000 + int(rand() * 30000)
  for (i = 0; i < 40000; i++) {
    t = 8 * 3600 + i
    stamp = sprintf("%02d:%02d:%02d", int(t / 3600) % 24, int(t / 60) % 60, t % 60)
    if (i == hit) printf "%s user=%s action=LOGIN_OK token=%s\n", stamp, who, flag
    else printf "%s user=%s action=%s token=%08x\n", stamp, u[1 + int(rand() * 10)], a[1 + int(rand() * 5)], int(rand() * 4294967295)
  }
}' > "$H/mission5/access.log"
{ printf 'An intruder logged in ONCE as:  %s\nTheir token is the flag.\n\n' "$who"; readme 5; } > "$H/mission5/README.txt"

# ---- step 6: base64 ----
F6=$(flag decoded); keep 6 "$F6"
mkdir -p "$H/mission6"
readme 6 > "$H/mission6/README.txt"
printf 'Decoded! Encoding is not encryption.\nFlag: %s\n' "$F6" | base64 -w 40 > "$H/mission6/message.b64"

# ---- the submit command ----
cat > /usr/local/bin/submit <<'SH'
#!/bin/bash
# Usage: submit <flag>   records your answer, then press CHECK in the instructions.
if [ -z "${1:-}" ]; then echo "Usage: submit CYBA{...}"; exit 1; fi
echo "$1" >> "$HOME/.answers"
echo "Recorded. Now press CHECK in the instructions panel."
SH
chmod 755 /usr/local/bin/submit

touch "$H/.answers"
# Clear the screen when player logs in, so the root lines that Killercoda types
# into the terminal (foreground.sh) disappear. /etc/profile.d runs for every
# login shell, whatever dotfiles the image gives the new user.
cat > /etc/profile.d/zz-linux-quest.sh <<'SH'
if [ "$(id -un)" = player ]; then case $- in *i*) clear ;; esac; fi
SH
chown -R player:player "$H"
touch /tmp/.quest-ready
